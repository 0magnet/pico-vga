package gvga

// NewFont creates a new Font structure
func NewFont(width, height, firstChar, lastChar uint8, data []byte) *Font {
	return &Font{
		Width:     width,
		Height:    height,
		FirstChar: firstChar,
		LastChar:  lastChar,
		Data:      data,
	}
}

// GetLine returns the font bitmap byte for character c at line
func (f *Font) GetLine(c uint8, line uint8) uint8 {
	return f.Data[int(c)*int(f.Height)+int(line)]
}

